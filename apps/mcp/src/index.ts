import express from 'express'
import cors from 'cors'
import { env } from './env.js'
import { createServer, resolveUserFromAuth } from './mcp-server.js'
import { ensureMcpAuthRoutes } from './mcp-auth.js'
import { StreamableHTTPServerTransport } from '@modelcontextprotocol/sdk/server/streamableHttp.js'

const app = express()

app.use(cors())
app.use(express.json({ limit: '10mb' }))

app.get('/health', (_req, res) => {
  res.json({ status: 'ok', service: 'payo-mcp', uptime: process.uptime() })
})

// ── ChatGPT plugin domain verification ────────────────────────────────────────
// OpenAI's Plugins portal asks us to serve a challenge token at
// /.well-known/openai-apps-challenge. It must be plain text — not JSON.
// The token is generated by the portal and changes per submission attempt,
// so we read it from OPENAI_APPS_CHALLENGE_TOKEN at request time (no redeploy
// needed once the variable is set on the host).
const CHALLENGE_PATHS = [
  '/.well-known/openai-apps-challenge',
  '/.well-known/openai-apps/.well-known/openai-apps',
]

for (const p of CHALLENGE_PATHS) {
  app.get(p, (_req, res) => {
    const token = process.env.OPENAI_APPS_CHALLENGE_TOKEN
    if (!token) {
      // Don't 404 while the user is still setting this up — the portal shows a
      // clearer error than a 404 does. Returning empty still fails verification,
      // but with a diagnosable log line.
      console.warn(`[domain-verification] token not set for ${p} (set OPENAI_APPS_CHALLENGE_TOKEN)`)
      res.status(404).type('text/plain').send('challenge token not configured')
      return
    }
    res.type('text/plain').send(token)
  })
}

// RFC 9728 protected resource metadata — tells MCP clients where to authenticate.
// Served dynamically so the canonical `resource` URL always matches the live host.
app.get('/.well-known/oauth-protected-resource', (req, res) => {
  const origin = process.env.PAYO_PUBLIC_ORIGIN || `${req.protocol}://${req.get('host')}`
  res.json({
    resource: `${origin}/mcp`,
    authorization_servers: [origin],
    scopes_supported: ['openid', 'email', 'profile'],
    bearer_methods_supported: ['header'],
    resource_documentation: 'https://payo.live',
  })
})

// ── OAuth 2.1 authorization server ────────────────────────────────────────────
// Serves /api/auth/* (authorize, token, register, userinfo) plus the
// /.well-known/oauth-authorization-server + /jwks.json discovery documents that
// the mcp() plugin mounts. These must live on the same origin as /mcp so the
// issuer and audience match what tokens are minted against.
await ensureMcpAuthRoutes(app)

// MCP Streamable HTTP transport — handles GET (SSE), POST (RPC), DELETE (session close)
app.all('/mcp', async (req, res) => {
  try {
    const authHeader = req.headers.authorization || (req.headers['x-api-key'] as string | undefined)
    const cookieHeader = req.headers.cookie
    const user = await resolveUserFromAuth(authHeader, cookieHeader)

    if (!user && env.MCP_REQUIRE_OAUTH === 'true') {
      // RFC 9728 challenge so the client knows where to start the OAuth flow.
      const origin = env.PAYO_MCP_PUBLIC_ORIGIN
      res.setHeader(
        'WWW-Authenticate',
        `Bearer resource_metadata="${origin}/.well-known/oauth-protected-resource"`,
      )
      res.status(401).json({ error: 'unauthorized' })
      return
    }

    // Detect MCP client from initialize handshake (e.g. "ChatGPT", "claude-code")
    // so tools can adapt responses (rich markdown + images vs compact CLI text).
    let clientName: string | undefined
    try {
      const body = req.body
      if (body?.method === 'initialize') {
        clientName = body?.params?.clientInfo?.name as string | undefined
      }
    } catch { /* ignore */ }

    const server = createServer(user, clientName)
    const transport = new StreamableHTTPServerTransport({
      sessionIdGenerator: undefined, // stateless — new server per request
    })

    res.on('close', () => {
      transport.close()
      server.close()
    })

    await server.connect(transport)
    await transport.handleRequest(req, res, req.body)
  } catch (error: any) {
    console.error('[MCP Error]:', error)
    if (!res.headersSent) {
      res.status(500).json({ error: 'Internal server error' })
    }
  }
})

app.listen(env.PORT, () => {
  console.log(`🚀 Payo MCP server running at http://localhost:${env.PORT}/mcp`)
})
